<#
.SYNOPSIS
  Snapshot the installed SRanipal runtime into vendor/ (untracked) and write
  docs/inventory.md: every PE file with version, size, SHA-256, machine,
  imports and export count, plus full export lists of the SR* API DLLs.

.EXAMPLE
  pwsh scripts/inventory.ps1
  pwsh scripts/inventory.ps1 -Source "D:\VIVE\SRanipal" -NoCopy
#>
param(
    [string]$Source = "C:\Program Files\VIVE\SRanipal",
    [switch]$NoCopy
)
$ErrorActionPreference = 'Stop'
$repo = Split-Path $PSScriptRoot -Parent
$vendor = Join-Path $repo 'vendor\SRanipal'
$peInfo = Join-Path $PSScriptRoot 'pe_info.py'

if (-not $NoCopy) {
    New-Item -ItemType Directory -Force $vendor | Out-Null
    robocopy $Source $vendor /MIR /NFL /NDL /NJH /NJS /NP | Out-Null
    if ($LASTEXITCODE -ge 8) { throw "robocopy failed ($LASTEXITCODE)" }
}

# Skip the Unity players' managed/runtime folders: stock Unity/Mono files.
$files = Get-ChildItem $Source -Recurse -File -Include *.dll, *.exe |
    Where-Object { $_.FullName -notmatch '\\(Managed|MonoBleedingEdge)\\' } |
    Sort-Object FullName

$rows = foreach ($f in $files) {
    $rel = $f.FullName.Substring($Source.Length + 1)
    $info = py -I $peInfo $f.FullName --json | ConvertFrom-Json
    [pscustomobject]@{
        Path    = $rel
        Version = $f.VersionInfo.FileVersion
        Size    = $f.Length
        Sha256  = (Get-FileHash $f.FullName -Algorithm SHA256).Hash.ToLower()
        Machine = $info.machine
        DotNet  = $info.dotnet
        Imports = $info.imports
        Exports = $info.exports
    }
}

$md = [System.Collections.Generic.List[string]]::new()
$md.Add('# SRanipal install inventory')
$md.Add('')
$md.Add("Generated by ``scripts/inventory.ps1`` from ``$Source`` on $(Get-Date -Format yyyy-MM-dd).")
$md.Add('Unity Managed/ and MonoBleedingEdge/ folders are skipped.')
$md.Add('')
$md.Add('| File | Version | Arch | .NET | Exports | Size | SHA-256 (first 16) |')
$md.Add('|---|---|---|---|---|---|---|')
foreach ($r in $rows) {
    $md.Add("| ``$($r.Path)`` | $($r.Version) | $($r.Machine) | $(if ($r.DotNet) {'yes'}) | $(@($r.Exports).Count) | $($r.Size) | ``$($r.Sha256.Substring(0,16))`` |")
}
$md.Add('')
$md.Add('## Imports (first-party modules)')
$md.Add('')
foreach ($r in $rows | Where-Object { $_.Path -notmatch '^(Qt5|opencv_|platforms\\|tools\\|SRanipalUpdateService\\)' }) {
    $md.Add("- ``$($r.Path)``: $((@($r.Imports)) -join ', ')")
}
$md.Add('')
$md.Add('## Exports of the SR API / runtime DLLs')
foreach ($r in $rows | Where-Object { $_.Path -match '^(ViveSR_|SRWorks_|EyeCamera|EyePrediction|LCamera|LPrediction|LipPrediction|USBDev)|eye_camera_device' -and @($_.Exports).Count -gt 0 }) {
    $md.Add('')
    $md.Add("### ``$($r.Path)``")
    $md.Add('')
    $md.Add('```')
    foreach ($e in $r.Exports) { $md.Add($e) }
    $md.Add('```')
}
Set-Content -Path (Join-Path $repo 'docs\inventory.md') -Value $md -Encoding utf8
Write-Host "wrote docs/inventory.md ($($rows.Count) files)"
